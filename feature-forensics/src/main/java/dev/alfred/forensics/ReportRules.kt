        "entropy" to "Spectral entropy",
        "envelope" to "HF envelope correlation",
        "header_bitrate" to "Header bitrate mismatch",
        "header_duration" to "Header duration mismatch",
        "hf" to "HF magnitude ratio",
        "hiss" to "Hiss level",
        "hiss_corr" to "Hiss correlation",
